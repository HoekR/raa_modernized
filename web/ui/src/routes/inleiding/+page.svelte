<section class="inleiding">
  <h1>Inleiding</h1>
  <p class="lede">
    Het <strong>Repertorium van Ambtenaren en Ambtsdragers 1428–1861</strong> ontsluit
    personen, functies, instellingen en aanstellingen in de Noordelijke Nederlanden.
    U zoekt via vier ingangen; de periode rechtsboven geldt overal.
  </p>

  <h2>Periodes</h2>
  <ul class="periods">
    <li><strong>Middeleeuwen</strong> — tot 1588</li>
    <li><strong>Republiek</strong> — 1588–1795</li>
    <li><strong>Bataafs-Franse tijd</strong> — 1795–1813</li>
    <li><strong>Negentiende eeuw</strong> — 1813–1861</li>
  </ul>

  <h2>Zoeken</h2>
  <p>
    Op <a href="/personen">Personen</a> en <a href="/aanstellingen">Aanstellingen</a> kunt u
    verfijnen met facetten (periode, functie, instelling, stand/adel, namens-velden).
    Bij geboorte- en sterfdata betekent <em>ca.</em> een onzekere bron-datum;
    <em>geschat</em> betekent afgeleid uit aanstellingen (geen bron-datum).
  </p>

  <h2>Datums bij instellingen en functies</h2>
  <p>
    “Eerste” en “laatste gedateerde aanstelling” zijn de vroegste en laatste
    <em>gedateerde</em> rijen in dit bestand. Onderbrekingen tussen institutionele
    contexten worden niet automatisch ingevuld.
  </p>

